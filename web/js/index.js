// 根据浏览器语言自动选择
let lang = (navigator.language || navigator.userLanguage || "")
  .toLowerCase()
  .startsWith("zh")
  ? "zh"
  : "en";
function setLang(next) {
  lang = next;
  const danmaku = document.querySelector(".hero-danmaku");
  if (lang === "zh") {
    document.getElementById("quarkDownload").style.display = "inline-flex";
    danmaku.style.display = "block";
  } else {
    danmaku.style.display = "none";
    document.getElementById("quarkDownload").style.display = "none";
  }
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.dataset.i18n;
    if (copy[lang][k]) el.textContent = copy[lang][k];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const k = el.dataset.i18nHtml;
    if (copy[lang][k]) el.innerHTML = copy[lang][k];
  });
  document.getElementById("langToggle").textContent =
    lang === "zh" ? "EN / 中文" : "中文 / EN";
  document
    .querySelectorAll(".compare input")
    .forEach((el, i) =>
      el.setAttribute(
        "aria-label",
        lang === "zh"
          ? i === 0
            ? "720p 画面对比滑块"
            : "1080p 画面对比滑块"
          : i === 0
          ? "720p image comparison slider"
          : "1080p image comparison slider"
      )
    );
}
setLang(lang);
document
  .getElementById("langToggle")
  .addEventListener("click", () => setLang(lang === "zh" ? "en" : "zh"));
document.querySelectorAll(".compare").forEach((box) => {
  const input = box.querySelector("input");
  function update() {
    box.style.setProperty("--split", input.value + "%");
  }
  input.addEventListener("input", update);
  update();
});
const lightbox = document.getElementById("themeLightbox"),
  lightboxImg = document.getElementById("lightboxImage"),
  lightboxCaption = document.getElementById("lightboxCaption"),
  closeLightbox = lightbox.querySelector(".lightbox-close");
function openThemePreview(trigger) {
  const src = trigger.dataset.lightbox;
  if (!src) return;
  lightboxImg.src = src;
  lightboxImg.alt = trigger.dataset.caption + " theme preview";
  lightboxCaption.textContent =
    (trigger.dataset.caption || "Theme") +
    " · " +
    (lang === "zh"
      ? "点击空白处或按 Esc 关闭"
      : "Click outside or press Esc to close");
  lightbox.classList.add("open");
  document.body.classList.add("lightbox-open");
  closeLightbox.focus();
}
function hideThemePreview() {
  lightbox.classList.remove("open");
  document.body.classList.remove("lightbox-open");
  lightboxImg.src = "";
}
document.querySelectorAll("[data-lightbox]").forEach((el) => {
  el.addEventListener("click", () => openThemePreview(el));
  el.addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      openThemePreview(el);
    }
  });
});
closeLightbox.addEventListener("click", hideThemePreview);
lightbox.addEventListener("click", (e) => {
  if (e.target === lightbox) hideThemePreview();
});
lightboxImg.addEventListener("click", hideThemePreview);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && lightbox.classList.contains("open"))
    hideThemePreview();
});

